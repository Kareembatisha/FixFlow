/** Mirrors the backend `RequestStatus` enum values. */
export const REQUEST_STATUSES = [
  'new',
  'reviewed',
  'assigned',
  'in_progress',
  'pending_review',
  'completed',
  'cancelled',
] as const;
export type RequestStatus = (typeof REQUEST_STATUSES)[number];

/** Mirrors the backend `RequestPriority` enum values. */
export const REQUEST_PRIORITIES = ['low', 'medium', 'high', 'urgent'] as const;
export type RequestPriority = (typeof REQUEST_PRIORITIES)[number];

/** Body of POST /service-requests. `customerId` is taken from the token, never sent. */
export interface CreateServiceRequestPayload {
  serviceTypeId: string;
  title: string;
  description: string;
  address: string;
  contactPhone: string;
  /** Optional. Omit it instead of sending an empty string. */
  preferredDate?: string;
}

/**
 * A service request as returned by the list, details and create endpoints.
 *
 * The API returns `serviceTypeId` only (no nested `serviceType`), so the display name is
 * resolved from the loaded service types. Fields that are not confirmed are optional.
 */
export interface ServiceRequest {
  id: string;
  /** Request code generated by the backend. */
  code: string;
  serviceTypeId: string;
  title: string;
  description: string;
  address: string;
  contactPhone: string;
  preferredDate?: string | null;
  status: RequestStatus;
  priority: RequestPriority;
  /** Unconfirmed (the list is sorted by it, but serialization is not verified). */
  createdAt?: string;
}

/** Query parameters of GET /service-requests. All optional. */
export interface ServiceRequestQuery {
  page?: number;
  limit?: number;
  status?: RequestStatus;
  priority?: RequestPriority;
  search?: string;
}
